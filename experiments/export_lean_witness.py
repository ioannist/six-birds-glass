"""Recompute exact Kovacs signatures and export byte-stable Lean lookup witnesses."""

from __future__ import annotations

import hashlib
import sys
from fractions import Fraction
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from sixbirds_glass.io.config import config_hash, load_config  # noqa: E402
from sixbirds_glass.pipeline.kovacs_witness import (  # noqa: E402
    build_kovacs_moment_witness_from_config,
)


def render_witness(config_path: Path) -> tuple[int, str]:
    config = load_config(config_path)
    witness = build_kovacs_moment_witness_from_config(config)
    if witness.separating_gap <= 0:
        raise ValueError("numeric witness has no separating future")
    namespace = f"GlassWitness.NumericN{witness.N}"
    values = [witness.current_value, witness.future_value_mu_k, witness.future_value_pi_eq]
    signature_sha = hashlib.sha256("\n".join(str(v) for v in values).encode()).hexdigest()
    result = f"""-- Generated by experiments/export_lean_witness.py; regenerate rather than edit.
-- Config: {config_path.relative_to(REPO_ROOT)}
-- Config sha256: {config_hash(config)}
-- Signature sha256: {signature_sha}
-- Scope: current mean energy and the declared {witness.probe_steps}-step energy probe.
-- Exact kernel evolution/tuning occurs in Python; Lean checks the exported rational
-- lookup separation and the corrected-core witness, strictness, and nonfactorization.
import GlassWitness.NumericCore

set_option maxRecDepth 100000
set_option maxHeartbeats 2000000

namespace {namespace}

def currentValue : Rat := {_rat(values[0])}
def futureMu : Rat := {_rat(values[1])}
def futureEq : Rat := {_rat(values[2])}

def futureReadout (h : Fin 2) : Rat := if h.val = 0 then futureMu else futureEq

theorem future_split : futureReadout 0 ≠ futureReadout 1 := by decide +kernel

theorem strict_refinement :
    DeclaredMemory.StrictRefinement
      (Numeric.core currentValue futureReadout) GlassInterface.mid :=
  Numeric.strict_refinement currentValue futureReadout future_split

theorem nonfactorization :
    ¬ ∃ f : Rat → Rat, ∀ h : Fin 2, f currentValue = futureReadout h :=
  Numeric.nonfactorization currentValue futureReadout future_split

theorem current_panel_not_futureSufficient :
    ¬ DeclaredMemory.FutureSufficient (Numeric.core currentValue futureReadout)
      (i := GlassInterface.mid)
      (fun _ : Fin 2 => currentValue) :=
  Numeric.current_panel_not_futureSufficient currentValue futureReadout future_split

end {namespace}
"""
    return witness.N, result


def _rat(value: Fraction) -> str:
    return f"({value.numerator} : Rat) / {value.denominator}"


if __name__ == "__main__":
    for name in ["gt6_shell_witness_n8.json", "kovacs_hump_default.json"]:
        n, rendered = render_witness(REPO_ROOT / "configs" / name)
        path = REPO_ROOT / "lean" / "GlassWitness" / f"NumericN{n}.lean"
        path.write_text(rendered)
        print(f"exported exact mean-energy witness N={n}")
