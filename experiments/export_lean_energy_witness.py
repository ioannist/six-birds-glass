"""Export the actual full-energy-law witness and every declared continuation."""

from __future__ import annotations

import hashlib
import sys
from fractions import Fraction
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from sixbirds_glass.io.config import config_hash, load_config  # noqa: E402
from sixbirds_glass.pipeline.energy_witness import (  # noqa: E402
    build_energy_mixture_witness_from_config,
)

CONFIG_PATH = REPO_ROOT / "configs/gt6_shell_witness_n8.json"
OUTPUT_PATH = REPO_ROOT / "lean/GlassWitness/EnergyN8.lean"


def _rat(value: Fraction) -> str:
    return f"({value.numerator} : Rat) / {value.denominator}"


def _table(name: str, values: list[Fraction]) -> str:
    branches = "\n".join(f"  | {i} => {_rat(v)}" for i, v in enumerate(values[:-1]))
    return (
        f"def {name} (i : Fin {len(values)}) : Rat :=\n"
        f"  match i.val with\n{branches}\n  | _ => {_rat(values[-1])}\n"
    )


def render_witness() -> str:
    config = load_config(CONFIG_PATH)
    w = build_energy_mixture_witness_from_config(config)
    horizons = list(w.future_values)
    if horizons != list(range(1, len(horizons) + 1)):
        raise ValueError("Lean export requires the complete integer horizon prefix")
    if any(a == b for a, b in w.future_values.values()):
        raise ValueError("an exported horizon does not separate the histories")
    current = [w.mixtures.energy_law[e] for e in range(w.N + 1)]
    plus = [a for a, _ in w.future_values.values()]
    minus = [b for _, b in w.future_values.values()]
    signature = hashlib.sha256(
        "\n".join(str(v) for v in (*current, *plus, *minus)).encode()
    ).hexdigest()
    tables = "\n".join(
        [_table("currentLaw", current), _table("futurePlus", plus), _table("futureMinus", minus)]
    )
    return f"""-- Generated by experiments/export_lean_energy_witness.py.
-- Regenerate rather than edit.
-- Config sha256: {config_hash(config)}
-- Exact observation-table sha256: {signature}
-- Scope: complete current energy law and continuation horizons {horizons[0]}..{horizons[-1]}.
-- Python replays the East preparation, convex stopping mixtures and kernel pushes.
-- Lean independently checks every exported rational split and its logical consequences.
import GlassWitness.EnergyCore

set_option maxRecDepth 100000
set_option maxHeartbeats 20000000

namespace GlassWitness.EnergyN8

{tables}
-- The Fin index τ denotes the physical continuation of τ.val + 1 steps.
def futureReadout (τ : Fin {len(horizons)}) (h : Fin 2) : Rat :=
  if h.val = 0 then futurePlus τ else futureMinus τ

theorem all_horizons_split :
    ∀ τ : Fin {len(horizons)}, futureReadout τ 0 ≠ futureReadout τ 1 := by decide +kernel

theorem strict_refinement :
    DeclaredMemory.StrictRefinement
      (Energy.core currentLaw futureReadout) GlassInterface.mid :=
  Energy.strict_refinement currentLaw futureReadout 0 (all_horizons_split 0)

theorem all_horizons_nonfactorization (τ : Fin {len(horizons)}) :
    ¬ ∃ f : (Fin {w.N + 1} → Rat) → Rat, ∀ h : Fin 2,
      f currentLaw = futureReadout τ h :=
  Energy.nonfactorization currentLaw futureReadout τ (all_horizons_split τ)

theorem current_law_not_futureSufficient :
    ¬ DeclaredMemory.FutureSufficient (Energy.core currentLaw futureReadout)
      (i := GlassInterface.mid) (fun _ : Fin 2 => currentLaw) :=
  Energy.current_law_not_futureSufficient
    currentLaw futureReadout 0 (all_horizons_split 0)

theorem energy_descriptor_not_futureSufficient {{State : Type}}
    (descriptor : (Fin {w.N + 1} → Rat) → State) :
    ¬ DeclaredMemory.FutureSufficient (Energy.core currentLaw futureReadout)
      (i := GlassInterface.mid) (fun _ : Fin 2 => descriptor currentLaw) :=
  Energy.energy_descriptor_not_futureSufficient
    currentLaw futureReadout 0 (all_horizons_split 0) descriptor

end GlassWitness.EnergyN8
"""


if __name__ == "__main__":
    OUTPUT_PATH.write_text(render_witness())
    print("exported exact full-energy-law N8 witness at every declared horizon")
